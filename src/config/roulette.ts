/**
 * Доступ к рулетке. Пилотный режим по адресу почты снят по решению владельца
 * продукта: рулетку включает и выключает переключатель в админке.
 * Остаётся единственное ограничение — запрет хода из-под подмены пользователя:
 * иначе администратор прокрутил бы чужой баланс.
 */
export function canUseRoulette(user: { isImpersonating?: boolean } | null): boolean {
  return Boolean(user) && !user!.isImpersonating
}
